const CONFIRM = "BACKFILL_TILE_ADHESIVE_CONTENT_BATCH1";
const ALL_MATS = Object.freeze(DATA.BATCH_MATS);
const CONTENT_FIELDS_EXACTLY = Object.freeze(["short_description", "full_description", "seo_title", "seo_description"]);
